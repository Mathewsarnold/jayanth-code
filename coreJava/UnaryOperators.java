public class UnaryOperators {
    public static void main (String [] args) {
        int n1 = 33;
        ++n1;

        System.out.println(n1);
        n1++;
        System.out.println(n1);
        System.out.println(n1++);
        System.out.println(n1);
        System.out.println(--n1);
        System.out.println(n1--);
        System.out.println(n1);

    }
}