public class BitwiseOperators {
    public static void main (String [] args) {
        // int num1 = 13;
        // int num2 = 17;
        int num1 = 5;
        int num2 = 7;

        System.out.println(num1&num2);
        System.out.println(num1|num2);
        System.out.println(num1^num2);

    }
}